import { ClerkProvider } from "@clerk/nextjs";
import type { Metadata } from "next";
import ApiAuthBridge from "@/components/auth/ApiAuthBridge";
import { requestAgency } from "@/lib/serverSession";
import { AgencySessionProvider } from "@/lib/session";
import "./globals.css"

export async function generateMetadata(): Promise<Metadata> {
  const branding = await requestAgency();
  if (branding) {
    return {
      title: branding.productName,
      description: branding.productName,
      ...(branding.logoDataUrl ? { icons: { icon: branding.logoDataUrl } } : {}),
    };
  }
  return {
    title: "Create Next App",
    description: "Generated by create next app",
  };
}

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  // For an agency customer the app runs without Clerk: they sign in
  // with the agency login (lib/session.tsx). Everywhere else, unchanged.
  const branding = await requestAgency();
  if (branding) {
    return (
      <html lang="en">
        <body className="antialiased" style={{ ["--agency-primary" as string]: branding.primaryColor }}>
          <AgencySessionProvider branding={branding}>{children}</AgencySessionProvider>
        </body>
      </html>
    );
  }

  return (
    <ClerkProvider>
      <html lang="en">
        <body className="antialiased">
          <ApiAuthBridge />
          {children}
        </body>
      </html>
    </ClerkProvider>
  );
}
